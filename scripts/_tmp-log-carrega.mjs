import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1512, height: 900 }, deviceScaleFactor: 2 });
await ctx.addInitScript(() => { window.__hgLog = []; });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:3003/nova/inici?active=first_contact', { waitUntil: 'load', timeout: 180000 });
await p.waitForTimeout(4000);
const log = await p.evaluate(() => window.__hgLog || []);
const t0 = log.length ? log[0].t : 0;
console.log(`entrades ${log.length}`);
for (const x of log) console.log(`+${String(x.t - t0).padStart(5)} ms  ${x.nom.padEnd(13)} ${JSON.stringify(x.valor)}`);
await b.close();
