import { chromium } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1920, height: 946 }, deviceScaleFactor: 1 });
await ctx.addInitScript(() => { try { window.sessionStorage.setItem('HG_MEGA_PAGE', JSON.stringify({ value: 1, expiresAt: Date.now() + 600000 })); } catch {} });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:3003/nova/inici?active=first_contact', { waitUntil: 'load', timeout: 180000 });
await p.waitForTimeout(3000);
await p.click('button:has(svg.lucide-search)').catch(() => {});
await p.waitForTimeout(9000);
const estat = () => p.evaluate(() => {
  const v1 = document.querySelector('[data-mega-page-viewport="1"]');
  const tira = v1.querySelector('[data-carrusel="1"]')?.firstElementChild?.firstElementChild;
  return getComputedStyle(tira).transform;
});
const info = await p.evaluate(() => {
  const v1 = document.querySelector('[data-mega-page-viewport="1"]');
  const el = v1.querySelector('#stripe-guide-right-arrow');
  const an = v1.querySelector('button[aria-label="Anterior"]');
  const q = el.getBoundingClientRect(), qa = an.getBoundingClientRect();
  const mid = (r) => [r.left + r.width / 2, r.top + r.height / 2];
  const [x, y] = mid(q); const [xa, ya] = mid(qa);
  const e1 = document.elementFromPoint(x, y); const e2 = document.elementFromPoint(xa, ya);
  return { v1Left: v1.getBoundingClientRect().left, dreta: { x, y, qui: e1 ? (e1.id || e1.tagName + '.' + String(e1.className).slice(0, 24)) : null }, esq: { x: xa, y: ya, qui: e2 ? (e2.getAttribute('aria-label') || e2.tagName) : null } };
});
console.log('abans', await estat(), JSON.stringify(info));
await p.mouse.click(info.dreta.x, info.dreta.y);
await p.waitForTimeout(1500);
console.log('despres clic DREITA', await estat());
await p.mouse.click(info.esq.x, info.esq.y);
await p.waitForTimeout(1500);
console.log('despres clic ESQUERRA', await estat());
await p.screenshot({ path: '_tmp-b2-p1-clic.png', clip: { x: 1300, y: 60, width: 260, height: 300 } });
await ctx.close();
await b.close();
