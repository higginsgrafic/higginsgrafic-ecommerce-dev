export function getCollectionItems(collectionId) {
  const col = COLLECTIONS[collectionId];
  if (!col || !col.columns || col.columns.length === 0) return [];
  return col.columns[0].items.filter(
    (it) => it !== CONTROL_TILE_BN && it !== CONTROL_TILE_ARROWS
  );
}
