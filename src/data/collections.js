const isPathItem = (v) => typeof v === 'string' && /\.(png|jpg|jpeg|webp)$/i.test(v);

function normalizeKey(value) {
  if (typeof value !== 'string') return '';
  return value.trim().toLowerCase()
    .replace(/[\u2010\u2011\u2012\u2013\u2014\u2212]/g, '-')
    .replace(/\s+/g, ' ')
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
}

