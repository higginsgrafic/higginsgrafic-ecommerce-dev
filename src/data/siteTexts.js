// Helper function to get nested text
export const getText = (path) => {
  return path.split('.').reduce((obj, key) => obj?.[key], siteTexts);
};

// Save to localStorage
export const saveTexts = (newTexts) => {
  localStorage.setItem('siteTexts', JSON.stringify(newTexts));
};

// Load from localStorage
export const loadTexts = () => {
  const saved = localStorage.getItem('siteTexts');
  return saved ? JSON.parse(saved) : siteTexts;
};

